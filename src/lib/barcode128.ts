const START_B = 104;
const START_C = 105;
const SWITCH_C = 99;
const STOP = 106;

/** يحوّل النص إلى سلسلة قيم CODE128 (مع رمز البداية والتدقيق والإيقاف). null إن تعذّر. */
function code128Values(text: string): number[] | null {
  const t = (text || '').trim();
  if (!t) return null;

  const vals: number[] = [];
  if (/^\d+$/.test(t) && t.length >= 4) {
    // أرقام فقط → وضع C (رقمان في كل رمز = باركود أقصر وأوضح).
    let rest = t;
    if (t.length % 2 === 1) {
      // طول فردي (مثل EAN-13): أول رقم بوضع B ثم التحويل إلى C.
      vals.push(START_B, t.charCodeAt(0) - 32, SWITCH_C);
      rest = t.slice(1);
    } else {
      vals.push(START_C);
    }
    for (let i = 0; i < rest.length; i += 2) vals.push(parseInt(rest.slice(i, i + 2), 10));
  } else {
    // نص عام → وضع B (ASCII 32-126 فقط).
    vals.push(START_B);
    for (const ch of t) {
      const c = ch.charCodeAt(0);
      if (c < 32 || c > 126) return null;
      vals.push(c - 32);
    }
  }

  // رقم التدقيق: (البداية + Σ القيمة×الموضع) mod 103.
  let sum = vals[0];
  for (let i = 1; i < vals.length; i++) sum += vals[i] * i;
  vals.push(sum % 103, STOP);
  return vals;
}

/**
 * يبني SVG لباركود CODE128. يُعيد null إن كان النص غير قابل للترميز.
 * الأبعاد تُضبط من CSS الخارجي (width/height) — الـ viewBox بوحدة "الموديول".
 */
export function code128Svg(text: string, barHeight = 30): string | null {
  const vals = code128Values(text);
  if (!vals) return null;

  const rects: string[] = [];
  let x = 0;
  for (const v of vals) {
    const pat = PATTERNS[v];
    for (let i = 0; i < pat.length; i++) {
      const w = Number(pat[i]);
      if (i % 2 === 0) rects.push(`<rect x="${x}" y="0" width="${w}" height="${barHeight}"/>`);
      x += w;
    }
  }
  const quiet = 10; // منطقة هادئة على الجانبين (ضرورية للمسح)
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-quiet} 0 ${x + quiet * 2} ${barHeight}" ` +
    `preserveAspectRatio="none" shape-rendering="crispEdges" fill="#000">${rects.join('')}</svg>`
  );
}
